def column(table_id: UUID, number: int, name: str, **options: object) -> Columns:
    values: dict[str, object] = dict(
        id=UUID(int=number),
        table_id=table_id,
        name=name,
        type="integer",
        custom_type=None,
        length=None,
        precision=None,
        scale=None,
        array_dimensions=0,
        nullable=True,
        primary_key=False,
        unique=False,
        auto_increment=False,
        unsigned=False,
        default=None,
        check=None,
        enum_values=[],
        sort_order=number,
        notice=None,
    )
    values.update(options)
    return Columns(**values)


